/// The meanings of one icon: whole-icon entries first (they are the most
/// specific), then each name word's meanings, de-duplicated in that order.
export function meaningsOf(base: string): string[] {
  const out: string[] = [];
  const seen = new Set<string>();
  const push = (m: string) => {
    if (!seen.has(m)) {
      seen.add(m);
      out.push(m);
    }
  };
  for (const m of ICON_MEANINGS[base] ?? []) push(m);
  for (const word of base.split("-")) {
    if (VARIANT_WORDS.has(word)) continue;
    for (const m of WORD_MEANINGS[word] ?? []) push(m);
  }
  return out;
}
